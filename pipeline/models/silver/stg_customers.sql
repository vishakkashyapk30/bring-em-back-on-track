-- CRM records, typed and standardised (one row per CRM record; a person can have two).
-- Protected attributes are NOT selected here; they live only in stg_customers_protected (fairness audit).
select
    crm_customer_id,
    nullif(duplicate_of_crm_id, '')                         as duplicate_of_crm_id,
    nullif(national_id_hash, '')                            as national_id_hash,
    {{ to_bool('is_deleted') }}                              as is_deleted,
    customer_status,
    try_cast(last_profile_update_ts as timestamp)           as last_profile_update_ts,
    first_name, last_name, preferred_name, full_name_raw,
    {{ last_token('last_name') }}                            as last_name_key,
    left({{ first_token('first_name') }}, 1)                 as first_initial,
    {{ first_token('first_name') }}                          as first_name_key,
    try_cast(date_of_birth as date)                         as dob,
    primary_phone_e164,
    {{ phone_digits('primary_phone_e164') }}                 as phone_digits,
    case when {{ to_bool('email_verified_flag') }} and not {{ to_bool('email_bounce_flag') }} then email end as email_clean,
    city, province_code, {{ postal('postal_code') }}         as postal, fsa, time_zone,
    {{ to_bool('returned_mail_flag') }}                      as returned_mail_flag,
    try_cast(customer_since_date as date)                   as customer_since_date,
    segment, employment_status, industry_naics2, employer_name, pay_frequency,
    try_cast(declared_annual_income as double)              as declared_annual_income,
    preferred_language,
    {{ to_bool('consent_call') }} as consent_call, {{ to_bool('consent_sms') }} as consent_sms,
    {{ to_bool('consent_email') }} as consent_email, {{ to_bool('consent_push') }} as consent_push,
    {{ to_bool('consent_letter') }} as consent_letter,
    permitted_call_start_local, permitted_call_end_local,
    {{ to_bool('sunday_contact_permitted') }}                as sunday_contact_permitted,
    {{ to_bool('internal_do_not_call_flag') }}               as internal_do_not_call_flag,
    {{ to_bool('cease_communication_flag') }}                as cease_communication_flag,
    {{ to_bool('third_party_authorised_flag') }}             as third_party_authorised_flag,
    {{ to_bool('credit_counselling_agency_flag') }}          as credit_counselling_agency_flag,
    {{ to_bool('legal_representative_flag') }}               as legal_representative_flag,
    {{ to_bool('power_of_attorney_flag') }}                  as power_of_attorney_flag,
    {{ to_bool('vulnerability_flag') }}                      as vulnerability_flag,
    vulnerability_source,
    try_cast(vulnerability_review_date as date)             as vulnerability_review_date,
    {{ to_bool('deceased_flag') }}                           as deceased_flag,
    {{ to_bool('bankruptcy_flag') }}                         as bankruptcy_flag,
    {{ to_bool('consumer_proposal_flag') }}                  as consumer_proposal_flag,
    {{ to_bool('fraud_victim_flag') }}                       as fraud_victim_flag
from {{ source('bronze', 'customers') }}
where {{ current_crm_filter() }}
