"""Generate one typed silver model per release table from the release's schema/schema.json.

Same table and column names as the release (so benchmark SQL works unchanged), declared types applied with
try_cast, dates and timestamps parsed across formats. Big history tables are views to save disk.

Run: python -m pipeline.gen_typed_models  (re-run only if the release schema changes; output is committed)
"""

from __future__ import annotations

import json
from pathlib import Path

from common.config import get_settings

HERE = Path(__file__).resolve().parent
OUT = HERE / "models" / "silver" / "typed"
VIEWS = {"loan_instalments", "transactions", "card_statements", "account_monthly_snapshot", "bureau_history",
         "salary_credit_history"}
# Columns that hold identifiers or codes with leading zeros stay text even if declared numeric.
KEEP_TEXT = {"src_customer_ref", "bank_subject_ref", "institution_number", "transit_number"}


def expr(col: dict) -> str:
    name, phys = col["name"], (col.get("physical_type") or "VARCHAR").upper()
    q = f'"{name}"'
    if name in KEEP_TEXT or phys.startswith("VARCHAR"):
        return f"{q}"
    if phys == "DATE":
        return f"{{{{ parse_date('{q}') }}}} as {q}"
    if phys.startswith("TIMESTAMP"):
        return f"{{{{ parse_ts('{q}') }}}} as {q}"
    if phys == "BOOLEAN":
        return f"(lower(cast({q} as varchar)) = 'true') as {q}"
    return f"try_cast({q} as {phys}) as {q}"


def main() -> None:
    schema = json.loads((get_settings().raw_dir / "maple_collections_release" / "schema" / "schema.json").read_text())
    OUT.mkdir(parents=True, exist_ok=True)
    for table, spec in schema.items():
        cols = ",\n    ".join(expr(c) for c in spec["columns"])
        mat = "view" if table in VIEWS else "table"
        sql = (f"-- GENERATED by pipeline/gen_typed_models.py from the release schema. Do not edit by hand.\n"
               f"-- {spec.get('description', '')}\n"
               f"{{{{ config(materialized='{mat}') }}}}\n"
               f"select\n    {cols}\nfrom {{{{ source('bronze', '{table}') }}}}\n")
        (OUT / f"{table}.sql").write_text(sql)
    print(f"wrote {len(schema)} models to {OUT}")


if __name__ == "__main__":
    main()
